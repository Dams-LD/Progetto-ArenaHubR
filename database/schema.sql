BEGIN;

CREATE TABLE public.profiles (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    avatar TEXT,
    ruolo TEXT NOT NULL DEFAULT 'UTENTE',
    CONSTRAINT profiles_username_length
        CHECK (CHAR_LENGTH(BTRIM(username)) BETWEEN 3 AND 30),
    CONSTRAINT profiles_username_trimmed
        CHECK (username = BTRIM(username)),
    CONSTRAINT profiles_ruolo_check
        CHECK (ruolo IN ('UTENTE', 'ADMIN'))
);

CREATE UNIQUE INDEX profiles_username_lower_uidx
    ON public.profiles (LOWER(username));


CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_username TEXT;
BEGIN
    v_username :=
        NULLIF(BTRIM(NEW.raw_user_meta_data ->> 'username'), '');

    IF v_username IS NULL THEN
        v_username :=
            'utente_' ||
            SUBSTR(REPLACE(NEW.id::TEXT, '-', ''), 1, 16);
    END IF;

    INSERT INTO public.profiles (
        id,
        username,
        avatar,
        ruolo
    )
    VALUES (
        NEW.id,
        v_username,
        NULL,
        'UTENTE'
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

REVOKE ALL ON FUNCTION public.handle_new_user()
    FROM PUBLIC, anon, authenticated;


CREATE TABLE public.tornei (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    gioco TEXT NOT NULL,
    categoria TEXT NOT NULL,
    descrizione TEXT NOT NULL,
    regole TEXT NOT NULL,
    data_ora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    posti_max INTEGER NOT NULL,
    stato TEXT NOT NULL DEFAULT 'aperto',

    CONSTRAINT tornei_nome_length
        CHECK (CHAR_LENGTH(BTRIM(nome)) BETWEEN 3 AND 100),

    CONSTRAINT tornei_gioco_length
        CHECK (CHAR_LENGTH(BTRIM(gioco)) BETWEEN 2 AND 50),

    CONSTRAINT tornei_categoria_not_empty
        CHECK (CHAR_LENGTH(BTRIM(categoria)) > 0),

    CONSTRAINT tornei_descrizione_length
        CHECK (CHAR_LENGTH(descrizione) <= 300),

    CONSTRAINT tornei_regole_length
        CHECK (CHAR_LENGTH(regole) <= 2000),

    CONSTRAINT tornei_posti_max_check
        CHECK (posti_max BETWEEN 2 AND 128),

    CONSTRAINT tornei_stato_check
        CHECK (stato IN ('aperto', 'chiuso', 'concluso'))
);


CREATE TABLE public.iscrizioni (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    utente_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,

    torneo_id INTEGER NOT NULL
        REFERENCES public.tornei(id) ON DELETE RESTRICT,

    data_iscrizione TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT iscrizioni_utente_torneo_unique
        UNIQUE (utente_id, torneo_id)
);


CREATE INDEX idx_tornei_categoria
    ON public.tornei (categoria);

CREATE INDEX idx_tornei_stato_data
    ON public.tornei (stato, data_ora);

CREATE INDEX idx_iscrizioni_torneo_data
    ON public.iscrizioni (torneo_id, data_iscrizione);


ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tornei ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.iscrizioni ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE
    public.profiles,
    public.tornei,
    public.iscrizioni
FROM anon, authenticated;

COMMIT;


